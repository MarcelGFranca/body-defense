"""Writes design/balance.md: every balance number (before and after the balance pass) and the playtest results.

Usage: python3 -I tools/write_balance_doc.py [before_commit]
"before" is read from git (default HEAD, the commit before the balance pass); "after" from the data folder.
"""
import json
import os
import re
import subprocess
import sys
from collections import defaultdict

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
BEFORE = sys.argv[1] if len(sys.argv) > 1 else "HEAD"
TOWERS = ["macrophage", "neutrophil", "mucus-cell", "platelet", "hypothalamus", "lysozyme", "interferon", "t-lymphocyte",
          "b-lymphocyte", "bone-marrow"]
ENEMIES = ["rhinovirus", "influenza", "sars-cov-2", "herpes-simplex", "hpv", "e-coli", "streptococcus-pyogenes",
           "staphylococcus-aureus", "helicobacter-pylori", "clostridioides-difficile", "hiv",
           "mycobacterium-tuberculosis", "neisseria-meningitidis"]


def read_after(path):
    return open(os.path.join(ROOT, path), encoding="utf-8").read()


def read_before(path):
    return subprocess.run(["git", "show", "%s:%s" % (BEFORE, path)], cwd=ROOT, capture_output=True, text=True).stdout


def scalar(text, key, default=0.0):
    match = re.search(r"^%s = (.+)$" % key, text, re.M)
    if not match:
        return default
    value = match.group(1).strip()
    try:
        return float(value)
    except ValueError:
        return value.strip('"')


def fmt(x):
    if isinstance(x, str):
        return x
    return ("%g" % round(x, 3))


def change(before, after):
    return fmt(after) if fmt(before) == fmt(after) else "%s → **%s**" % (fmt(before), fmt(after))


def waves(text):
    result = []
    for block in re.findall(r"\[sub_resource type=\"Resource\".*?(?=\n\[)", text, re.S):
        start = scalar(block, "start_time")
        interval = scalar(block, "spawn_interval", 1.0)
        entries = [(m.group(2), int(m.group(1))) for m in re.finditer(r'"count": (\d+),\s*"enemy": "([a-z0-9-]+)"', block)]
        if entries:
            result.append((start, interval, entries))
    return result


def games(folder):
    path = os.path.join(ROOT, "playtests", folder, "games.jsonl")
    if not os.path.exists(path):
        return []
    return [json.loads(line) for line in open(path, encoding="utf-8") if line.strip()]


def win(rows):
    return 100.0 * sum(g["result"] == "won" for g in rows) / len(rows) if rows else 0.0


def main():
    out = []
    w = out.append
    w("# Balance data\n")
    w("Every number that decides how hard the game is, before and after the balance pass, and what 1000 recorded games say about it. "
      "Changed values show as `before → **after**`. Generated by `tools/write_balance_doc.py` from the data files and `playtests/`.\n")

    # --- results
    base, med, easy, hard = games("baseline_1000"), games("medium_1000"), games("easy_1000"), games("hard_1000")
    w("## 1. How the games were played\n")
    w("- Each recorded game is played by a bot that builds towers in one of ten ways: `smart`, `smart_calls` (also calls waves early), "
      "`damage_only`, `balanced_mix`, `few_strong` (half of the slots), `worst_slots` (worst coverage first), `random_a`, `random_b`, "
      "`support_heavy` (slow, root, block and mark towers) and `cheap` (only the cheapest tower).")
    w("- The bots have human-like noise (they build a little late, sometimes pick another tower or swap two slots).")
    w("- The games are run by the game itself without a screen and at high speed (the simulation has no randomness), 1000 games in about 4 minutes.")
    w("- **Before** = `baseline_1000` (1000 games, Medium, original numbers). **After** = `medium_1000`, `easy_1000` and `hard_1000` (1000 games each, final numbers). "
      "Each level has 100 games per difficulty, which is a margin of error of about ±10 points.\n")

    w("## 2. Results\n")
    w("### Win rate by level (all strategies, %)\n")
    w("| Level | Before (Medium) | After: Easy | After: Medium | After: Hard |")
    w("|---|---|---|---|---|")
    for n in range(1, 11):
        cells = []
        for data in (base, easy, med, hard):
            rows = [g for g in data if g["level"] == n]
            cells.append("%.0f" % win(rows) if rows else "-")
        name = next((g["level_name"] for g in med if g["level"] == n), str(n))
        w("| %d %s | %s | %s | %s | %s |" % (n, name, cells[0], cells[1], cells[2], cells[3]))
    for label, data in (("Before (Medium)", base), ("After: Easy", easy), ("After: Medium", med), ("After: Hard", hard)):
        good = [g for g in data if g["strategy"] in ("smart", "balanced_mix", "damage_only")]
        if data:
            w("") if False else None
    w("")
    w("| Summary | Before (Medium) | Easy | Medium | Hard |")
    w("|---|---|---|---|---|")
    def row(label, fn):
        w("| %s | %s |" % (label, " | ".join(fn(d) if d else "-" for d in (base, easy, med, hard))))
    row("Win rate, all strategies", lambda d: "%.0f%%" % win(d))
    row("Win rate, the three careful strategies", lambda d: "%.0f%%" % win([g for g in d if g["strategy"] in ("smart", "balanced_mix", "damage_only")]))
    row("Average body health left", lambda d: "%.1f / %d" % (sum(g["health"] for g in d) / len(d), d[0]["health_max"]))
    row("Average game length", lambda d: "%.0f s" % (sum(g["time"] for g in d) / len(d)))
    w("")

    w("### Win rate by strategy (Medium, %)\n")
    w("| Strategy | Before | After |")
    w("|---|---|---|")
    names = sorted({g["strategy"] for g in med}, key=lambda s: -win([g for g in med if g["strategy"] == s]))
    for s in names:
        w("| %s | %.0f | %.0f |" % (s, win([g for g in base if g["strategy"] == s]), win([g for g in med if g["strategy"] == s])))
    w("")

    def tower_stats(data):
        damage, built, with_game = defaultdict(float), defaultdict(int), defaultdict(int)
        costs = {}
        for g in data:
            for t, a in g["damage_by_tower"].items():
                damage[t] += a
            for t, c in g["towers_built"].items():
                built[t] += c
                with_game[t] += 1
        return damage, built, with_game
    w("### Towers: damage that took health away, per amino acid spent (Medium)\n")
    w("| Tower | Before | After | Share of all damage after (%) |")
    w("|---|---|---|---|")
    stats = {name: tower_stats(d) for name, d in (("base", base), ("med", med))}
    total_after = sum(stats["med"][0].values()) or 1.0
    for t in TOWERS:
        cells = []
        for key, text_path in (("base", lambda t: read_before("data/towers/%s.tres" % t)), ("med", lambda t: read_after("data/towers/%s.tres" % t))):
            cost = scalar(text_path(t), "cost")
            damage, built, _ = stats[key]
            spent = built[t] * cost
            cells.append("%.1f" % (damage[t] / spent) if spent and damage[t] else "0 (support)")
        w("| %s | %s | %s | %.0f |" % (t, cells[0], cells[1], 100.0 * stats["med"][0][t] / total_after))
    w("")

    def leaks(data):
        killed, leaked = defaultdict(int), defaultdict(int)
        for g in data:
            for e, c in g["kills"].items():
                killed[e] += c
            for e, c in g["leaks"].items():
                leaked[e] += c
        return killed, leaked
    kb, lb = leaks(base)
    ka, la = leaks(med)
    w("### Enemies: share that got out (Medium, %)\n")
    w("| Enemy | Before | After |")
    w("|---|---|---|")
    for e in ENEMIES:
        pb = 100.0 * lb[e] / max(1, kb[e] + lb[e])
        pa = 100.0 * la[e] / max(1, ka[e] + la[e])
        w("| %s | %.1f | %.1f |" % (e, pb, pa))
    w("")

    # --- data
    w("## 3. Difficulties\n")
    w("| | Easy | Medium | Hard |")
    w("|---|---|---|---|")
    d = {i: read_after("data/difficulties/%s.tres" % i) for i in ("easy", "medium", "hard")}
    for label, key in (("Starting amino acids", "start_amino"), ("Body health", "body_health"), ("Enemy health", "enemy_health"),
                       ("Enemy speed", "enemy_speed"), ("Amino acids dropped", "reward"), ("Time between waves", "wave_time")):
        w("| %s | ×%s | ×%s | ×%s |" % (label, fmt(scalar(d["easy"], key, 1.0)), fmt(scalar(d["medium"], key, 1.0)), fmt(scalar(d["hard"], key, 1.0))))
    w("")

    w("## 4. Towers\n")
    w("| Tower | Damage type | Cost | Range | Damage | Interval (s) | Damage per second | Other |")
    w("|---|---|---|---|---|---|---|---|")
    for t in TOWERS:
        b, a = read_before("data/towers/%s.tres" % t), read_after("data/towers/%s.tres" % t)
        def v(key, default=0.0):
            return change(scalar(b, key, default), scalar(a, key, default))
        dps_b = scalar(b, "attack_damage") / max(0.01, scalar(b, "attack_interval", 1.0)) or scalar(b, "dot_damage")
        dps_a = scalar(a, "attack_damage") / max(0.01, scalar(a, "attack_interval", 1.0)) or scalar(a, "dot_damage")
        other = []
        for key, label in (("slow_percent", "slow %"), ("root_seconds", "root s"), ("root_targets", "root targets"), ("dot_damage", "dot/s"), ("dot_seconds", "dot s"),
                           ("mark_bonus", "mark"), ("mark_seconds", "mark s"), ("mark_targets", "mark targets"),
                           ("summon_interval", "summon every s"), ("summon_cap", "units max"), ("unit_health", "unit health"), ("unit_damage", "unit dps")):
            if scalar(a, key) or scalar(b, key):
                other.append("%s %s" % (label, v(key)))
        mobile = " (mobile)" if scalar(a, "mobility", "fixed") == "mobile" else ""
        w("| %s%s | %s | %s | %s | %s | %s | %s | %s |" % (t, mobile, scalar(a, "damage_type", "none"), v("cost"), v("range_px", 80.0),
                                                           v("attack_damage"), v("attack_interval", 1.0), change(dps_b, dps_a), ", ".join(other) or "-"))
    w("")

    w("## 5. Enemies\n")
    w("| Enemy | Type | Role | Health | Speed | Body damage | Reward | Armor % | Trait numbers |")
    w("|---|---|---|---|---|---|---|---|---|")
    for e in ENEMIES:
        b, a = read_before("data/enemies/%s.tres" % e), read_after("data/enemies/%s.tres" % e)
        def v(key, default=0.0):
            return change(scalar(b, key, default), scalar(a, key, default))
        params = re.search(r"^trait_params = (\{.*?\})$", a, re.M | re.S)
        params_text = re.sub(r"\s+", " ", params.group(1)) if params else "-"
        w("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (e, scalar(a, "type", "virus"), scalar(a, "role", "-"), v("health", 1.0), v("speed", 1.0),
                                                            v("body_damage", 1.0), v("amino_acid_reward", 1.0), v("armor_percent"), params_text))
    w("")

    w("## 6. Levels\n")
    w("| Level | Name | Slots | Boss | Towers | Starting amino acids | Waves | Body health (Medium) |")
    w("|---|---|---|---|---|---|---|---|")
    for n in range(1, 11):
        b, a = read_before("data/levels/level_%d.tres" % n), read_after("data/levels/level_%d.tres" % n)
        slots = len(re.search(r"slots = PackedVector2Array\(([^)]*)\)", a).group(1).split(",")) // 2
        towers = len(re.findall(r'"[a-z-]+"', re.search(r"tower_ids = \[([^\]]*)\]", a).group(1)))
        boss = scalar(a, "boss_id", "")
        w("| %d | %s | %d | %s | %d | %s | %d | %s |" % (n, scalar(a, "display_name", ""), slots, boss or "-", towers,
                                                         change(scalar(b, "starting_amino_acids"), scalar(a, "starting_amino_acids")),
                                                         len(waves(a)), fmt(scalar(a, "body_health", 1.0))))
    w("")
    w("### Waves of every level\n")
    w("Each wave: start time in seconds (before the difficulty), seconds between two enemies, and the enemies as `count` (before → after).\n")
    for n in range(1, 11):
        b, a = read_before("data/levels/level_%d.tres" % n), read_after("data/levels/level_%d.tres" % n)
        wb, wa = waves(b), waves(a)
        w("**Level %d, %s**\n" % (n, scalar(a, "display_name", "")))
        w("| Wave | Starts at (s) | Every (s) | Enemies |")
        w("|---|---|---|---|")
        for i, (start, interval, entries) in enumerate(wa):
            bstart, binterval, bentries = wb[i] if i < len(wb) else (start, interval, [])
            old = dict(bentries)
            text = ", ".join("%s %s" % (e, change(old.get(e, 0), c)) for e, c in entries)
            w("| %d | %s | %s | %s |" % (i + 1, change(bstart, start), change(binterval, interval), text))
        w("")
    path = os.path.join(ROOT, "design", "balance.md")
    open(path, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("wrote", os.path.relpath(path, ROOT), len(out), "lines")


if __name__ == "__main__":
    main()
